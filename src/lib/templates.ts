export function classifyRootCause(
  name: string,
  keywords: string[],
  habitat: Habitat,
): { rootCategory: string; defense: string } {
  const text = `${name} ${keywords.join(' ')}`.toLowerCase();
  const hit = ROOT_RULES.find((r) => r.match.some((m) => text.includes(m)));
  const category = hit?.category ?? ROOT_BY_HABITAT[habitat];
  return {
    rootCategory: category,
    defense: DEFENSE[category] ?? DEFENSE[ROOT_BY_HABITAT[habitat]],
  };
}

/**
 * 三步排查 = 栖息地专属建议 + 通用三步
 * 最终产出 4 条：第 1 条为栖息地专属，后 3 条为通用排查动作。
 */
export function makeGuide(
  name: string,
  habitat: Habitat,
  isOnline: boolean,
  keywords: string[] = [],
): BugGuide {
  const safeName = name || '这只 Bug';
  const reproHint = isOnline
    ? '线上环境优先：先按「用户操作路径 → 触发时间点 → 受影响账号」三段式最小化复现路径，别一上来就加日志'
    : '先在干净环境里最小化复现路径：砍掉无关分支、固定输入数据，确认它是否真的可稳定复现';

  const steps = [
    `【${habitat}专属】${pick(HABITAT_ADVICE[habitat])}`,
    `最小化复现路径：${reproHint}`,
    `对比最近变更与日志：把最近一次发布、配置改动、依赖升级和 ${safeName} 首次出现的时间点对上，日志按时间线排一遍`,
    `准备回滚与监控：确认回滚方案和开关是否可用，同时补上告警与埋点，别让它二次作案时你还在猜`,
  ];

  const { rootCategory, defense } = classifyRootCause(safeName, keywords, habitat);

  return {
    steps,
    review: {
      root: `根因是什么？—— ${safeName} 触发的直接原因是哪一行代码、哪一个配置，还是哪一次变更？把「表象 → 直接原因 → 根本原因」写清楚，不要停在表象。`,
      impact: `影响有多大？—— 影响了多少用户 / 多少请求 / 多长时间？是否涉及资金、数据一致性或合规风险？线上事故需要给出时间线和止损动作。`,
      prevention: `怎么打疫苗？—— 需要补什么测试、什么监控、什么兜底开关？把「这次靠人肉发现」改成「下次靠系统报警」。`,
    },
    vaccines: makeVaccines(habitat),
    rootCategory,
    defense,
  };
}

